class TestFolderEntity:
    """Tests for Folder entity dataclass"""

    def test_create_new(self):
        """Test create_new factory method."""
        from domains.folder.entities import Folder, FolderType, FolderColor

        folder = Folder.create_new(
            workspace_id="ws_123",
            folder_type=FolderType.PROJECT,
            name="My Folder",
            created_by="user_456",
            color=FolderColor.BLUE,
        )

        assert folder.workspace_id == "ws_123"
        assert folder.folder_type == FolderType.PROJECT
        assert folder.name == "My Folder"
        assert folder.created_by == "user_456"
        assert folder.color == FolderColor.BLUE
        assert folder.sort_order == 0
        # Note: ID is generated by database, not by create_new
        assert folder.id is None
        # created_at/updated_at are set by database
        assert folder.created_at is None
        assert folder.updated_at is None

    def test_create_new_default_color(self):
        """Test create_new uses SLATE as default color."""
        from domains.folder.entities import Folder, FolderType, FolderColor

        folder = Folder.create_new(
            workspace_id="ws_123",
            folder_type=FolderType.ASSET,
            name="Assets",
            created_by="user_456",
        )

        assert folder.color == FolderColor.SLATE

    def test_to_dict(self):
        """Test to_dict method."""
        from domains.folder.entities import Folder, FolderType, FolderColor

        folder = Folder(
            id="folder_abc",
            workspace_id="ws_123",
            folder_type=FolderType.PROJECT,
            name="Test Folder",
            color=FolderColor.EMERALD,
            sort_order=5,
            created_by="user_456",
            created_at=datetime(2026, 1, 28, 10, 0, 0),
            updated_at=datetime(2026, 1, 28, 12, 0, 0),
        )

        result = folder.to_dict()

        assert result["id"] == "folder_abc"
        assert result["workspace_id"] == "ws_123"
        assert result["folder_type"] == "project"
        assert result["name"] == "Test Folder"
        assert result["color"] == "emerald"
        assert result["sort_order"] == 5
        assert result["created_by"] == "user_456"
        assert "created_at" in result
        assert "updated_at" in result

    def test_from_dict(self):
        """Test from_dict method."""
        from domains.folder.entities import Folder, FolderType, FolderColor

        data = {
            "id": "folder_xyz",
            "workspace_id": "ws_789",
            "folder_type": "asset",
            "name": "My Assets",
            "color": "violet",
            "sort_order": 3,
            "created_by": "user_abc",
            "created_at": "2026-01-28T10:00:00",
            "updated_at": "2026-01-28T12:00:00",
        }

        folder = Folder.from_dict(data)

        assert folder.id == "folder_xyz"
        assert folder.workspace_id == "ws_789"
        assert folder.folder_type == FolderType.ASSET
        assert folder.name == "My Assets"
        assert folder.color == FolderColor.VIOLET
        assert folder.sort_order == 3
        assert folder.created_by == "user_abc"


