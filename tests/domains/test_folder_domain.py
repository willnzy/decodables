class TestFolderService:
    """Tests for FolderService business logic"""

    @pytest.fixture
    def mock_repository(self):
        """Create a mock folder repository."""
        return AsyncMock()

    @pytest.fixture
    def folder_service(self, mock_repository):
        """Create a FolderService with mocked repository."""
        from domains.folder.service import FolderService
        return FolderService(mock_repository)

    @pytest.mark.asyncio
    async def test_create_folder(self, folder_service, mock_repository):
        """Test creating a folder."""
        from domains.folder.entities import Folder, FolderType, FolderColor

        mock_repository.get_by_workspace_and_name.return_value = None
        mock_repository.count_items.return_value = 0

        created_folder = Folder(
            id="new_folder_id",
            workspace_id="ws_123",
            folder_type=FolderType.PROJECT,
            name="New Folder",
            color=FolderColor.BLUE,
            sort_order=0,
            created_by="user_456",
        )
        mock_repository.create.return_value = created_folder

        result = await folder_service.create_folder(
            workspace_id="ws_123",
            folder_type=FolderType.PROJECT,
            name="New Folder",
            created_by="user_456",
            color=FolderColor.BLUE,
        )

        assert result.name == "New Folder"
        assert result.workspace_id == "ws_123"
        mock_repository.create.assert_called_once()

    @pytest.mark.asyncio
    async def test_create_folder_duplicate_name_db_constraint(self, folder_service, mock_repository):
        """Test creating a folder with duplicate name - handled by DB constraint."""
        from domains.folder.entities import FolderType, FolderColor

        # Simulate database constraint error
        mock_repository.create.side_effect = Exception("duplicate key value violates unique constraint")

        with pytest.raises(Exception, match="duplicate"):
            await folder_service.create_folder(
                workspace_id="ws_123",
                folder_type=FolderType.PROJECT,
                name="Existing Folder",
                created_by="user_456",
            )

    @pytest.mark.asyncio
    async def test_list_folders(self, folder_service, mock_repository):
        """Test listing folders."""
        from domains.folder.entities import Folder, FolderType, FolderColor

        mock_folders = [
            Folder(id="f1", workspace_id="ws_123", folder_type=FolderType.PROJECT,
                   name="Folder A", color=FolderColor.SLATE, sort_order=0, created_by="user"),
            Folder(id="f2", workspace_id="ws_123", folder_type=FolderType.PROJECT,
                   name="Folder B", color=FolderColor.BLUE, sort_order=1, created_by="user"),
        ]
        mock_repository.get_by_workspace.return_value = mock_folders

        result = await folder_service.list_folders("ws_123", FolderType.PROJECT)

        assert len(result) == 2
        assert result[0].name == "Folder A"
        assert result[1].name == "Folder B"
        mock_repository.get_by_workspace.assert_called_once_with("ws_123", FolderType.PROJECT)

