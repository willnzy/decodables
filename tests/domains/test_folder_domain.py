    @pytest.mark.asyncio
    async def test_update_folder(self, folder_service, mock_repository):
        """Test updating a folder."""
        from domains.folder.entities import Folder, FolderType, FolderColor

        # Setup: existing folder for name conflict check
        existing_folder = Folder(
            id="folder_id",
            workspace_id="ws_123",
            folder_type=FolderType.PROJECT,
            name="Old Name",
            color=FolderColor.SLATE,
            sort_order=0,
            created_by="user",
        )
        mock_repository.get_by_id.return_value = existing_folder
        mock_repository.get_by_workspace_and_name.return_value = None  # No conflict

        updated_folder = Folder(
            id="folder_id",
            workspace_id="ws_123",
            folder_type=FolderType.PROJECT,
            name="Updated Name",
            color=FolderColor.VIOLET,
            sort_order=0,
            created_by="user",
        )
        mock_repository.update_partial.return_value = updated_folder

        result = await folder_service.update_folder(
            folder_id="folder_id",
            name="Updated Name",
            color=FolderColor.VIOLET,
        )

        assert result.name == "Updated Name"
        assert result.color == FolderColor.VIOLET

    @pytest.mark.asyncio
    async def test_reorder_folders(self, folder_service, mock_repository):
        """Test reordering folders."""
